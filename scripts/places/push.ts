// Upserts data/candidates.json into public.place_candidates (unique source+source_id).
// With NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY: upserts via supabase-js.
// Without the service key: writes data/candidates.sql (idempotent
// insert ... on conflict do update) for `psql`/SQL editor instead. Review
// fields (status, name, notes, difficulty, ...) are never overwritten.
//
// Run: npm run places:push [-- --sql]   (--sql forces the SQL file even with a key)
import { writeFileSync } from 'node:fs'
import { createClient } from '@supabase/supabase-js'
import { dataPath, readCandidates } from './lib/files'
import type { Candidate } from './lib/types'

const COLS = [
  'source',
  'source_id',
  'source_url',
  'image_remote_url',
  'lat',
  'lng',
  'heading',
  'author',
  'license',
  'attribution',
  'captured_at',
  'width',
  'height',
  'title',
  'suggested_name',
] as const

type Row = Record<(typeof COLS)[number], string | number | null>

function toRow(c: Candidate): Row {
  return {
    source: c.source,
    source_id: c.source_id,
    source_url: c.source_url,
    image_remote_url: c.image_remote_url,
    lat: c.lat,
    lng: c.lng,
    heading: c.heading,
    author: c.author,
    license: c.license,
    attribution: c.attribution,
    captured_at: c.captured_at,
    width: c.width,
    height: c.height,
    title: c.title,
    suggested_name: c.suggested_name,
  }
}

function sqlLit(v: string | number | null): string {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null'
  return `'${v.replace(/'/g, "''")}'`
}

function writeSql(rows: Row[]): string {
  const file = dataPath('candidates.sql')
  // Re-pushing must never reset curated fields: the pin (lat/lng/heading) and
  // the license (which may carry a "(cropped, text blurred)" change note).
  const KEEP_CURATED = new Set(['source', 'source_id', 'lat', 'lng', 'heading', 'license'])
  const updates = COLS.filter((c) => !KEEP_CURATED.has(c))
    .map((c) => `${c} = excluded.${c}`)
    .concat('updated_at = now()')
    .join(',\n  ')
  const chunks: string[] = ['-- Generated by scripts/places/push.ts — idempotent upsert of review candidates.', 'begin;']
  for (let i = 0; i < rows.length; i += 200) {
    const values = rows
      .slice(i, i + 200)
      .map((r) => `  (${COLS.map((c) => (c === 'captured_at' && r[c] ? `${sqlLit(r[c])}::timestamptz` : sqlLit(r[c]))).join(', ')})`)
      .join(',\n')
    chunks.push(`insert into public.place_candidates (${COLS.join(', ')})\nvalues\n${values}\non conflict (source, source_id) do update set\n  ${updates};`)
  }
  chunks.push('commit;')
  writeFileSync(file, chunks.join('\n\n') + '\n', 'utf8')
  return file
}

async function main() {
  const rows = readCandidates().map(toRow)
  if (!rows.length) {
    console.log('data/candidates.json is empty — run a fetch script first.')
    return
  }
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key || process.argv.includes('--sql')) {
    const file = writeSql(rows)
    console.log(`${!key ? 'SUPABASE_SERVICE_ROLE_KEY is not set — ' : ''}wrote ${rows.length} upserts to ${file} (nothing was sent to Supabase).`)
    console.log('Apply it to the intended database (local stack first), e.g. psql "$DB_URL" -f data/candidates.sql')
    return
  }
  console.log(`Upserting ${rows.length} candidates to ${new URL(url).host} ...`)
  const sb = createClient(url, key, { auth: { persistSession: false } })
  for (let i = 0; i < rows.length; i += 200) {
    // New candidates only: existing rows keep their reviewed/curated values.
    const { error } = await sb
      .from('place_candidates')
      .upsert(rows.slice(i, i + 200), { onConflict: 'source,source_id', ignoreDuplicates: true })
    if (error) throw new Error(`upsert failed at ${i}: ${error.message}`)
    console.log(`  ${Math.min(i + 200, rows.length)}/${rows.length}`)
  }
  console.log('done')
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
